import { CategoryId } from './catalog';

/**
 * Нумерология по дате рождения — число жизненного пути (Life Path Number).
 *
 * Каждое число «резонирует» с одной из четырёх сфер жизни Виктора, что и
 * связывает нумерологический разбор с колесом баланса: природная сила человека
 * сопоставляется с тем, насколько эта сфера развита на его колесе.
 */
export interface LifePath {
  number: number;
  title: string;
  /** Короткая суть (одной строкой). */
  essence: string;
  /** Развёрнутое описание для полной версии. */
  description: string;
  strengths: string[];
  /** Сфера жизни, с которой резонирует число. */
  sphere: CategoryId;
  /** Почему именно эта сфера. */
  sphereReason: string;
}

/** Сводит число к 1–9, сохраняя мастер-числа 11, 22, 33. */
export function reduceNumber(n: number): number {
  while (n > 9 && n !== 11 && n !== 22 && n !== 33) {
    n = String(n)
      .split('')
      .reduce((sum, ch) => sum + Number(ch), 0);
  }
  return n;
}

/** Считает число жизненного пути по ISO-дате (YYYY-MM-DD). null — если дата некорректна. */
export function computeLifePath(iso: string): number | null {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso ?? '');
  if (!m) return null;
  const [, year, month, day] = m;
  const digitSum = (s: string) => s.split('').reduce((sum, ch) => sum + Number(ch), 0);
  const parts = [month, day, year].map((p) => reduceNumber(digitSum(p)));
  return reduceNumber(parts[0] + parts[1] + parts[2]);
}

