/**
 * Каталог продуктов Виктора.
 *
 * Все продукты строго распределены по четырём сферам жизни.
 * Чтобы добавить новый продукт — просто добавьте объект в массив `products`
 * нужной категории. Карточки, модальные окна, оплата и диагностика
 * «Колесо баланса» подхватят его автоматически.
 */

export type CategoryId = 'mental' | 'family' | 'financial' | 'physical';

export interface Product {
  id: string;
  title: string;
  /** Краткое описание для карточки */
  summary: string;
  /** Полное описание для модального окна */
  description: string;
  /** Стоимость в валюте `currency` */
  price: number;
  currency: string;
  /** Что входит в продукт */
  features: string[];
  /** Формат: курс / интенсив / гайд и т.д. */
  format: string;
  /** Длительность / объём */
  duration: string;
  /** Идентификатор курса в GetCourse для автоматической выдачи доступа */
  getcourseId: string;
  /** Stripe Price ID для оформления оплаты */
  stripePriceId: string;
  /** Метка «хит продаж» / «новинка» */
  badge?: string;
}

export interface Category {
  id: CategoryId;
  /** Порядковый номер (для нумерации секций) */
  index: string;
  title: string;
  /** Подзаголовок-направление */
  tagline: string;
  description: string;
  /** Акцентный цвет секции (premium-палитра) */
  accent: string;
  accentSoft: string;
  /** Имя SVG-иконки */
  icon: 'mind' | 'family' | 'finance' | 'body';
  products: Product[];
}

